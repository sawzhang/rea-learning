import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import assert from 'node:assert/strict';
import { mergeCoverage } from './merge-coverage.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const output = resolve(root, 'results/06-coverage-merge');
mkdirSync(output, { recursive: true });
// Regenerate both real captures; do not consume a possibly stale report.
const execution = spawnSync(process.execPath, [resolve(root, 'scripts/run-coverage-lab.mjs')], { encoding: 'utf8', timeout: 60000, maxBuffer: 64*1024*1024 });
writeFileSync(resolve(output, 'capture.stdout.log'), execution.stdout ?? '');
writeFileSync(resolve(output, 'capture.stderr.log'), execution.stderr ?? '');
if (execution.error) throw execution.error;
assert.equal(execution.status, 0, execution.stderr);
const report = JSON.parse(readFileSync(resolve(root, 'results/05-function-coverage/report.json'), 'utf8'));
const captures = Object.entries(report.scenarios).map(([capture_id, scenario]) => ({ capture_id, source_sha256: report.source_sha256, node_version: report.node_version, offset_units: report.offset_units, items: scenario.items }));
const merged = mergeCoverage(captures);
assert.deepEqual(merged, mergeCoverage([...captures].reverse()), 'Order must not affect sum');
const byName = new Map(merged.map(item => [item.name,item]));
assert.equal(byName.get('double').invocation_count,3);
assert.equal(byName.get('choose').invocation_count,2);
assert.equal(byName.get('unused').invocation_count,1);
const source = readFileSync(resolve(root, 'labs/05-function-coverage/target/logic.js'), 'utf8');
const probes = ["return 'positive';", "return 'non-positive';"].map(text => {
  const offset = source.indexOf(text); assert.ok(offset >= 0);
  const counts = captures.map(c => mergeCoverage([c]).find(item => item.name === 'choose').segments.find(s => s.startOffset <= offset && offset < s.endOffset).count);
  const merged_count = byName.get('choose').segments.find(s => s.startOffset <= offset && offset < s.endOffset).count;
  assert.equal(merged_count, 1);
  assert.deepEqual([...counts].sort(), [0,1]);
  return { text, offset, counts, merged_count };
});
assert.throws(() => mergeCoverage([captures[0],captures[0]]), /Duplicate capture ID/);
const changed = structuredClone(captures); changed[1].source_sha256 = '0'.repeat(64);
assert.throws(() => mergeCoverage(changed), /Source digest mismatch/);
const incomplete = structuredClone(captures); incomplete[1].items.pop();
assert.throws(() => mergeCoverage(incomplete), /Incomplete function inventory/);
const crossing = structuredClone(captures); const ranges = crossing[0].items.find(item => item.name === 'choose').ranges;
const start = ranges[0].startOffset;
ranges.push({startOffset:start+1,endOffset:start+10,count:1},{startOffset:start+5,endOffset:start+15,count:1});
assert.throws(() => mergeCoverage(crossing), /Crossing ranges/);
const result = { authority: 'analyst inference over caller-owned V8 captures', source_sha256: report.source_sha256, node_version: report.node_version, static_evidence_id: report.static_evidence_id, capture_ids: captures.map(c=>c.capture_id), merged, branch_probes: probes, selected_function_coverage: Object.fromEntries([...captures.map(c => [c.capture_id, `${c.items.filter(item => item.count > 0).length}/${c.items.length}`]), ['merged', `${merged.filter(item => item.invocation_count > 0).length}/${merged.length}`]]), selected_branch_probe_coverage: Object.fromEntries([...captures.map((c,index) => [c.capture_id, `${probes.filter(p => p.counts[index] > 0).length}/${probes.length}`]), ['merged', `${probes.filter(p => p.merged_count > 0).length}/${probes.length}`]]), validation: { order_invariance:true, duplicate_rejected:true, digest_mismatch_rejected:true, missing_inventory_rejected:true, crossing_ranges_rejected:true } };
writeFileSync(resolve(output,'report.json'), JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
